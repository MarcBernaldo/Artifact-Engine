"""WTFBins -> the programs that look malicious and are not (v0.7.105).

    python -m artifact_engine.core.lol_import wtfbins <wtfbins-main.zip>

WTFBins (https://wtfbins.wtf, MIT) documents legitimate software that behaves
like an intrusion: SCCM running base64 PowerShell, a VPN client running
`whoami` as SYSTEM, a document scanner whose binary is called `Bloodhound.exe`.
Its pages are prose, one per entry, so this keeps from each the programs it is
ABOUT: every `<name>.exe` its title or text names, less the system binaries
those programs merely run (`whoami.exe`, `cmd.exe`, `powershell.exe` -- any
LOLBAS binary, plus a few Windows processes) -- an entry about a program that
runs `whoami` must not mark every `whoami`.

The result, `data/assets/wtfbins.yaml`, annotates the hunts' rows
(`handlers/_wtfbins.py`); it never removes one and never lowers its severity: a
name is all it matches on, and Silver Bullet's `Bloodhound.exe` shares its name
with the real BloodHound. The note tells the analyst where to look.
"""

from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path

import yaml

ASSET = "wtfbins.yaml"
SOURCE = "https://github.com/mttaggart/wtfbins"
SITE = "https://wtfbins.wtf"

_PAGE = re.compile(r"(?:^|/)content/(\d+)\.md$")
_EXE = re.compile(r"(?<![\w.-])([A-Za-z0-9][\w.-]*\.exe)\b", re.IGNORECASE)
# Windows's own processes the entries mention as what a program touches or
# imitates (Teramind's `dwm.exe`, an Everyone share in `explorer.exe`).
# A Windows binary an entry names because a program impersonates it (Noregon's
# `spoolsv.exe` in the wrong folder) or runs it (`ipconfig`, `tasklist`) is never
# marked: the real one would inherit the note.
_SYSTEM = {"explorer.exe", "dwm.exe", "lsass.exe", "svchost.exe", "whoami.exe", "cmd.exe",
           "powershell.exe", "pwsh.exe", "conhost.exe", "services.exe", "winlogon.exe",
           "spoolsv.exe", "ipconfig.exe", "systeminfo.exe", "tasklist.exe", "attrib.exe",
           "mpnotify.exe", "net.exe", "net1.exe", "netstat.exe", "hostname.exe", "quser.exe"}


def _front(text: str) -> tuple[dict, str]:
    parts = text.split("+++", 2)
    if len(parts) < 3:
        return {}, text
    meta = {}
    for key in ("id", "title"):
        m = re.search(rf'^{key}\s*=\s*"?([^"\n]*)"?\s*$', parts[1], re.MULTILINE)
        if m:
            meta[key] = m.group(1).strip()
    return meta, parts[2]


def entries(pages: list[str], system: set[str]) -> list[dict]:
    out = []
    for text in pages:
        meta, body = _front(text)
        if not meta.get("id") or not meta.get("title"):
            continue
        names = []
        for n in _EXE.findall(meta["title"] + "\n" + body):
            n = n.lower()
            if n not in system and n not in names:
                names.append(n)
        if not names:
            continue                                     # about behaviour, not a program
        summary = " ".join(body.split("<!-- more -->", 1)[0].split())[:200]
        out.append({"id": int(meta["id"]), "title": meta["title"], "binaries": names,
                    "summary": summary, "url": f"{SITE}/{meta['id']}"})
    return sorted(out, key=lambda e: e["id"])


def from_zip(archive: Path, lolbas: set[str]) -> list[dict]:
    pages = []
    with zipfile.ZipFile(archive) as z:
        for info in z.infolist():
            if _PAGE.search(info.filename) and info.file_size < 256 * 1024:
                pages.append(z.read(info).decode("utf-8", errors="replace"))
    return entries(pages, _SYSTEM | {b.lower() for b in lolbas})


def render(items: list[dict], source_date: str, total: int) -> str:
    lines = [
        "# GENERATED by `python -m artifact_engine.core.lol_import wtfbins` -- do not edit.",
        f"# Source: WTFBins, {SOURCE} (retrieved {source_date}).",
        "# WTFBins is licensed MIT. Legitimate programs that behave like an intrusion:",
        f"# {len(items)} of the site's {total} entries name a program of their own.",
        "entries:",
    ]
    for e in items:
        lines += [f"  - id: {e['id']}",
                  f"    title: {json.dumps(e['title'], ensure_ascii=False)}",
                  f"    binaries: {json.dumps(e['binaries'])}",
                  f"    summary: {json.dumps(e['summary'], ensure_ascii=False)}",
                  f"    url: {json.dumps(e['url'])}"]
    return "\n".join(lines) + "\n"


def lolbas_names(assets: Path) -> set[str]:
    try:
        data = yaml.safe_load((Path(assets) / "lolbas.yaml").read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return set()
    return {str(b).lower() for b in data.get("binaries") or []}
