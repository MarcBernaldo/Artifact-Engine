"""WTFBins notes for the hunts' rows (v0.7.105).

`wtfbins.yaml` (generated by `core/lol_wtfbins.py`) lists legitimate programs
that behave like an intrusion. A row about one of them gets a `known_benign`
note -- the entry's title and link -- and nothing else changes: the match is on
a file name alone, and a name is easy to share (Silver Bullet's `Bloodhound.exe`
and the real BloodHound), so the row keeps its severity and the analyst checks
the path or the parent the note describes.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from artifact_engine.core.lol_wtfbins import ASSET


def load(assets: Path) -> dict[str, str]:
    """{program name: "WTFBins: <title> <url>"}, or {} without the asset."""
    try:
        data = yaml.safe_load((Path(assets) / ASSET).read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return {}
    notes: dict[str, str] = {}
    for e in data.get("entries") or []:
        note = f"WTFBins: {e.get('title', '')} {e.get('url', '')}".strip()
        for name in e.get("binaries") or []:
            notes.setdefault(str(name).lower(), note)
    return notes


def program(command: str) -> str:
    """The file name a command line starts with, lower-case."""
    c = str(command or "").strip()
    first = c[1:].split('"', 1)[0] if c.startswith('"') else c.split(" ", 1)[0]
    return first.replace("/", "\\").rsplit("\\", 1)[-1].lower()
